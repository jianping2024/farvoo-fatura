  let current = 'zh';

  function normalize(raw) {
    const s = String(raw || '').toLowerCase();
    if (s === 'en' || s === 'english') return 'en';
    if (s === 'pt' || s.indexOf('portug') === 0) return 'pt';
    return 'zh';
  }

  function t(key) {
    const b = BUNDLES[current] || BUNDLES.zh;
    if (b[key] != null) return b[key];
    const zh = BUNDLES.zh[key];
    return zh != null ? zh : key;
  }

  /** ONLY interpolation: replace {name} from vars. */
  function fmt(key, vars) {
    let s = t(key);
    if (!vars) return s;
    return s.replace(/\{([a-zA-Z0-9_]+)\}/g, function (_, k) {
      return vars[k] != null ? String(vars[k]) : '';
    });
  }

  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (!key) return;
      const type = el.getAttribute('data-i18n-type');
      const val = type ? fmt(key, { type: type }) : t(key);
      const attr = el.getAttribute('data-i18n-attr');
      if (attr) {
        if (attr === 'placeholder' && (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA')) el.placeholder = val;
        else el.setAttribute(attr, val);
        return;
      }
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.value = val;
      } else {
        el.textContent = val;
      }
    });
    scope.querySelectorAll('[data-i18n-html]').forEach((el) => {
      const key = el.getAttribute('data-i18n-html');
      if (!key) return;
      el.innerHTML = t(key);
    });
    document.documentElement.lang = current === 'zh' ? 'zh-Hans' : current;
  }

  function setLocale(loc) {
    current = normalize(loc);
    apply(document);
    return current;
  }

  function getLocale() {
    return current;
  }

  function bundleKeys() {
    return Object.keys(BUNDLES.zh);
  }

  global.FiscalAdminI18n = { t, fmt, apply, setLocale, getLocale, normalize, bundleKeys };
